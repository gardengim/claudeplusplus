"""Regenerate src/cc_keys.rs, the Claude Code settings shown in /config, from the settings reference.

    curl -sL https://code.claude.com/docs/en/settings-reference.md -o /tmp/ref.md
    python3 -I tools/gen_cc_settings.py /tmp/ref.md > src/cc_keys.rs

Keeps every key a user, project or local settings file can set (managed-only and ~/.claude.json keys are
left out). A parent object whose sub-keys have their own entries (`sandbox`, `permissions`) is left out too.
"""
import json
import re
import sys

# Topic heading in the reference -> tab name in the panel.
TABS = {
    "Model and responses": "Model",
    "Permission settings": "Permissions",
    "Sandbox settings": "Sandbox",
    "Memory and context": "Context",
    "Interface and terminal": "Interface",
    "Git and attribution": "Git",
    "Hooks and automation": "Hooks",
    "Plugins and skills": "Plugins",
    "MCP": "MCP",
    "Agents, sessions, and worktrees": "Agents",
    "Remote, desktop, and notifications": "Remote",
    "Authentication and providers": "Auth",
    "Updates and versioning": "Updates",
    "Tools": "Tools",
    "Privacy and telemetry": "Privacy",
}

# Keys that only change Claude Code's own terminal UI, which claude++ replaces: still editable (plain
# `claude` reads them), but marked so nobody expects claude++ to change.
TUI = set("""autoScrollEnabled axScreenReader companyAnnouncements editorMode emojiCompletionEnabled fileSuggestion
footerLinksRegexes keybindingFlavor maxProseWidth prefersReducedMotion promptSuggestionEnabled showClearContextOnPlanAccept
showTurnDuration spellcheck spinnerTipsEnabled spinnerTipsOverride spinnerVerbs subagentStatusLine syntaxHighlightingDisabled
terminalProgressBarEnabled terminalTitleFromRename theme timeFormat timeZone tui verbose viewMode vimInsertModeRemaps
voice voiceEnabled wheelScrollAccelerationEnabled bashEditDiffEnabled""".split())


def plain(s):
    s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)  # links -> their text
    s = re.sub(r"^> ?(\[!(\w+)\])?", lambda m: m[2].capitalize() + ":" if m[2] else "", s, flags=re.M)  # callouts
    s = s.replace("**", "").replace("`", "")
    return re.sub(r"\s+", " ", s).strip()


def parse(src):
    topic, out = None, []
    for b in re.split(r"\n(?=#{2,3} )", src):
        head, _, body = b.partition("\n")
        if head.startswith("## "):
            topic = head[3:].strip()
            continue
        m = re.match(r"### `([^`]+)`", head)
        if not m or topic not in TABS:
            continue
        field = lambda name: (re.search(r"\*\*" + name + r"\*\*: ([^\n]*)", body) or [None, ""])[1]
        typ = field("Type")
        opts = []
        t = re.search(r"\*\*Type\*\*: [^\n]*\n((?:  [^\n]*\n)*)", body)
        for line in (t[1] if t else "").splitlines():
            o = re.match(r"\s+\* `([^`]+)`", line)
            if o:
                opts.append(o[1])
        scope = re.search(r"\*\*Scope\*\*: \[?`([^`]+)`", body)
        desc = body.strip().split("\n\n")[0]
        out.append(dict(key=m[1], topic=topic, type=typ, opts=opts, scope=scope[1] if scope else "", default=field("Default"), desc=desc))
    return out


def kind(x):
    t = x["type"]
    tl = t.lower()
    if tl.startswith("boolean"):
        return "Bool"
    if tl.startswith(("object", "array")):
        return "Json"
    if tl.startswith("the string"):
        return 'Choice(&["' + re.findall(r'"([^"]+)"', t)[0] + '"])'
    choices = [o.strip('"') for o in x["opts"] if o.startswith('"')]
    if not choices and tl.startswith("string") and "such as" not in tl:
        choices = re.findall(r'`"([^"`]+)"`', t.split(".")[0])
        if len(choices) < 2:
            choices = []
    choices = [c for c in dict.fromkeys(choices) if "<" not in c]
    if choices:
        return "Choice(&[" + ", ".join(json.dumps(c) for c in choices) + "])"
    if tl.startswith(("number", "integer", "positive integer", "non-negative")):
        return "Number"
    if tl.startswith("string"):
        return "Text"
    return "Json"


def main():
    keys = [x for x in parse(open(sys.argv[1]).read()) if x["scope"] not in ("Managed", "Global config", "")]
    names = {x["key"] for x in keys}
    keys = [x for x in keys if not any(n.startswith(x["key"] + ".") for n in names)]
    tabs = list(dict.fromkeys(TABS[x["topic"]] for x in keys))
    print("// @generated by tools/gen_cc_settings.py from the Claude Code settings reference; do not edit by hand.\n")
    print("use crate::settings::{CcKey, Kind::*};\n")
    print("pub const TABS: &[&str] = &[" + ", ".join(json.dumps(t) for t in tabs) + "];\n")
    print("pub const KEYS: &[CcKey] = &[")
    for x in keys:
        help = plain(x["desc"])
        if x["default"]:
            help += " Default: " + plain(x["default"]).rstrip(".") + "."
        print(f'    CcKey {{ key: {json.dumps(x["key"])}, tab: {tabs.index(TABS[x["topic"]]) + 1}, kind: {kind(x)}, scope: {json.dumps(x["scope"])}, tui: {str(x["key"] in TUI).lower()}, help: {json.dumps(help, ensure_ascii=False)} }},')
    print("];")


main()
